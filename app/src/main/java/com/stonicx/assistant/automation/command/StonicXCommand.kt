package com.stonicx.assistant.automation.command

sealed class StonicXCommand {
    data class PlayYouTube(val query: String) : StonicXCommand()
    data class SearchYouTube(val query: String) : StonicXCommand()
    data class OpenApp(val packageName: String) : StonicXCommand()
    data class WhatsAppMessage(val contact: String, val message: String) : StonicXCommand()
    data class WhatsAppCall(val contact: String, val video: Boolean) : StonicXCommand()
    data class WhatsAppDeleteMessage(val contact: String?, val forEveryone: Boolean) : StonicXCommand()
    object SubscribeChannel : StonicXCommand()
    object ToggleFullscreen : StonicXCommand()
    data class Brightness(val level: Int, val isRelative: Boolean = false, val delta: Int = 0) : StonicXCommand()
    data class Volume(val level: Int, val isRelative: Boolean = false, val delta: Int = 0) : StonicXCommand()
    data class Flash(val enabled: Boolean) : StonicXCommand()
    data class Remember(val text: String) : StonicXCommand()
    data class Forget(val query: String) : StonicXCommand()
    object WhatDoYouRemember : StonicXCommand()
    data class SearchWeb(val query: String) : StonicXCommand()
    data class OpenWebUrls(val urls: List<String>) : StonicXCommand()
    data class PhoneCall(val contactOrNumber: String) : StonicXCommand()
    object PauseMedia : StonicXCommand()
    object ResumeMedia : StonicXCommand()
    object NextMedia : StonicXCommand()
    object PreviousMedia : StonicXCommand()
    data class ConfirmAction(val confirmed: Boolean) : StonicXCommand()
    data class DisambiguationChoice(val choice: String) : StonicXCommand()
    object RecallBirthday : StonicXCommand()
    object RecallFavoriteSong : StonicXCommand()
    object RecallRoutine : StonicXCommand()
    object GoToBackground : StonicXCommand()
}
